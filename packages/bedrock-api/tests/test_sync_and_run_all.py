"""Unit tests for the standards mirror (`sync_standards`) and the platform
audit suite orchestrator (`run_all`)."""
from __future__ import annotations

from pathlib import Path

import pytest

from bedrock.tools import run_all, sync_standards

_HEADER = "<!-- AUTOGENERATED MIRROR FROM BEDROCK PLATFORM. DO NOT EDIT LOCALLY. -->"


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _make_source(tmp_path: Path) -> Path:
    source = tmp_path / "bedrock-source"
    _write(source / "docs" / "standards" / "s001-no-duplicate-ui-code.md", "# Standard S001\n\nBody.\n")
    _write(source / "docs" / "standards" / "s012-dual-pin-platform-governance.md", "# Standard S012\n\nBody.\n")
    _write(source / "docs" / "standards" / "s100-domain-standard-authoring.md", "# Standard S100\n\nBody.\n")
    return source


def _make_target(tmp_path: Path) -> Path:
    target = tmp_path / "consumer"
    target.mkdir()
    return target


# ---------------------------------------------------------------------------
# sync_standards
# ---------------------------------------------------------------------------


def test_sync_copies_canonical_standards_with_header(tmp_path: Path):
    source = _make_source(tmp_path)
    target = _make_target(tmp_path)

    exit_code = sync_standards.main(["--root", str(target), "--source", str(source)])

    assert exit_code == 0
    mirrored = (target / "docs" / "standards" / "s001-no-duplicate-ui-code.md").read_text(encoding="utf-8")
    assert mirrored.startswith(_HEADER)
    assert "Body." in mirrored
    assert (target / "docs" / "standards" / "s100-domain-standard-authoring.md").exists()


def test_sync_preserves_consumer_domain_standards(tmp_path: Path):
    source = _make_source(tmp_path)
    target = _make_target(tmp_path)
    domain_standard = target / "docs" / "standards" / "s101-collectit-listing-rules.md"
    _write(domain_standard, "# Standard S101\n\nConsumer-owned content.\n")

    sync_standards.main(["--root", str(target), "--source", str(source)])

    assert domain_standard.read_text(encoding="utf-8") == "# Standard S101\n\nConsumer-owned content.\n"


def test_sync_check_returns_zero_when_mirrors_are_fresh(tmp_path: Path, capsys):
    source = _make_source(tmp_path)
    target = _make_target(tmp_path)
    sync_standards.main(["--root", str(target), "--source", str(source)])
    capsys.readouterr()

    exit_code = sync_standards.main(["--root", str(target), "--source", str(source), "--check"])

    assert exit_code == 0


def test_sync_check_returns_one_on_drift(tmp_path: Path, capsys):
    source = _make_source(tmp_path)
    target = _make_target(tmp_path)
    sync_standards.main(["--root", str(target), "--source", str(source)])
    drifted = target / "docs" / "standards" / "s001-no-duplicate-ui-code.md"
    drifted.write_text(drifted.read_text(encoding="utf-8") + "\nLocal edit.\n", encoding="utf-8")
    capsys.readouterr()

    exit_code = sync_standards.main(["--root", str(target), "--source", str(source), "--check"])
    output = capsys.readouterr().out

    assert exit_code == 1
    assert "s001-no-duplicate-ui-code.md" in output


def test_sync_check_returns_one_on_missing_mirror(tmp_path: Path, capsys):
    source = _make_source(tmp_path)
    target = _make_target(tmp_path)

    exit_code = sync_standards.main(["--root", str(target), "--source", str(source), "--check"])
    output = capsys.readouterr().out

    assert exit_code == 1
    assert "s001-no-duplicate-ui-code.md" in output


