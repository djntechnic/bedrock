class _FakeAuditModule:
    def __init__(self, exit_code: int) -> None:
        self.exit_code = exit_code
        self.calls: list[list[str]] = []

    def main(self, argv: list[str] | None = None) -> int:
        self.calls.append(list(argv or []))
        return self.exit_code


def test_run_all_returns_zero_when_all_audits_pass(tmp_path: Path, monkeypatch):
    fakes = [("s001", _FakeAuditModule(0)), ("s002", _FakeAuditModule(0))]
    monkeypatch.setattr(run_all, "AUDIT_MODULES", fakes)

    exit_code = run_all.main(["--root", str(tmp_path)])

    assert exit_code == 0


def test_run_all_returns_one_when_an_audit_fails(tmp_path: Path, monkeypatch):
    fakes = [("s001", _FakeAuditModule(0)), ("s002", _FakeAuditModule(1))]
    monkeypatch.setattr(run_all, "AUDIT_MODULES", fakes)

    exit_code = run_all.main(["--root", str(tmp_path)])

    assert exit_code == 1


def test_run_all_returns_two_on_configuration_error(tmp_path: Path, monkeypatch):
    fakes = [("s001", _FakeAuditModule(2)), ("s002", _FakeAuditModule(1))]
    monkeypatch.setattr(run_all, "AUDIT_MODULES", fakes)

    exit_code = run_all.main(["--root", str(tmp_path)])

    assert exit_code == 2


def test_run_all_respects_fail_fast(tmp_path: Path, monkeypatch):
    first = _FakeAuditModule(1)
    second = _FakeAuditModule(0)
    monkeypatch.setattr(run_all, "AUDIT_MODULES", [("s001", first), ("s002", second)])

    run_all.main(["--root", str(tmp_path), "--fail-fast"])

    assert len(first.calls) == 1
    assert len(second.calls) == 0


def test_run_all_without_fail_fast_runs_every_audit(tmp_path: Path, monkeypatch):
    first = _FakeAuditModule(1)
    second = _FakeAuditModule(0)
    monkeypatch.setattr(run_all, "AUDIT_MODULES", [("s001", first), ("s002", second)])

    run_all.main(["--root", str(tmp_path)])

    assert len(first.calls) == 1
    assert len(second.calls) == 1


def test_run_all_json_output_reports_every_audit_status(tmp_path: Path, monkeypatch, capsys):
    fakes = [("s001", _FakeAuditModule(0)), ("s002", _FakeAuditModule(1))]
    monkeypatch.setattr(run_all, "AUDIT_MODULES", fakes)
    capsys.readouterr()

    run_all.main(["--root", str(tmp_path), "--json"])
    output = capsys.readouterr().out

    assert '"s001"' in output
    assert '"s002"' in output
    assert "PASS" in output
    assert "FAIL" in output
